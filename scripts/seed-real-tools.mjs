async function main() {
  console.log(`🚀 Seeding ${REAL_TOOLS.length} real curated developer tools...`);
  console.log(`📡 Target Supabase URL: ${supabaseUrl}`);

  let successCount = 0;

  for (const tool of REAL_TOOLS) {
    const embeddingText = `${tool.title} ${tool.name || ''} ${tool.slug || ''} Category: ${tool.category} Subcategories: ${(tool.subcategories || []).join(', ')} ${tool.description} Use cases: ${(tool.use_cases || []).join(', ')} Tags: ${(tool.tags || []).join(', ')} Languages: ${(tool.languages || []).join(', ')} Frameworks: ${(tool.frameworks || []).join(', ')}`;
    const embedding = generateLocalEmbedding(embeddingText);

    const payload = {
      ...tool,
      embedding,
    };

    // Check if tool with slug or title already exists
    const { data: existing } = await supabase
      .from('tools')
      .select('id')
      .or(`slug.eq.${tool.slug},title.eq.${tool.title}`)
      .limit(1);

    if (existing && existing.length > 0) {
      const { error: updateErr } = await supabase
        .from('tools')
        .update(payload)
        .eq('id', existing[0].id);

      if (updateErr) {
        console.warn(`⚠️ Error updating ${tool.title}:`, updateErr.message);
      } else {
        successCount++;
        process.stdout.write('.');
      }
    } else {
      const { error: insertErr } = await supabase
        .from('tools')
        .insert(payload);

      if (insertErr) {
        console.warn(`⚠️ Error inserting ${tool.title}:`, insertErr.message);
      } else {
        successCount++;
        process.stdout.write('+');
      }
    }
  }

  console.log(`\n\n✅ Done! Successfully seeded/updated ${successCount} tools in Supabase with pgvector embeddings.`);
}

main().catch(err => {
  console.error('Fatal error during seed:', err);
  process.exit(1);
});

